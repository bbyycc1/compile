export function normalizeLang(v: string | null | undefined): Lang {
  if (v === 'zh-Hans' || v === 'zh-CN') return 'zh-Hans';
  if (v === 'zh-Hant' || v === 'zh-TW' || v === 'zh-HK') return 'zh-Hant';
  if (v === 'es' || v === 'es-ES') return 'es';
  return 'en';
}

